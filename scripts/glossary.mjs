// Глоссарий: сборка и проверка. Источник — web/i18n/glossary.js.
//   node scripts/glossary.mjs          собрать таблицу и страницы Docs, проверить подписи
//   node scripts/glossary.mjs --check  только проверить (ничего не пишет)
// Пишет: web/i18n/GLOSSARY.md (таблица для людей и переводчиков) и страницу-словарик Docs на каждом языке
// (docsite/src/content/docs/[<язык>/]docs/terms.mdx). Подсказки терминов в студии собирает сам glossary.js при загрузке.
// Проверяет: у каждого подчёркнутого термина интерфейса есть подсказка на каждом языке; у каждого термина заполнены
// перевод и объяснение; в подписях нет форм, которые глоссарий запрещает (поле avoid).
import { readFileSync, writeFileSync, readdirSync, mkdirSync } from 'node:fs';
import vm from 'node:vm';

const root = new URL('..', import.meta.url).pathname, checkOnly = process.argv.includes('--check');
const ctx = { window: {} };
const langsOnDisk = readdirSync(`${root}web/i18n`).filter((f) => /^[a-z]{2}\.js$/.test(f)).map((f) => f.slice(0, 2));
for (const l of langsOnDisk) vm.runInNewContext(readFileSync(`${root}web/i18n/${l}.js`, 'utf8'), ctx);
vm.runInNewContext(readFileSync(`${root}web/i18n/glossary.js`, 'utf8'), ctx);
const D = ctx.window.MQ_DICTS, G = ctx.window.MQ_GLOSSARY, problems = [];
const NAME = { en: 'English', ru: 'Русский' };
const UI = { en: { title: 'Terms at a glance', desc: 'Every term of the studio in one table: what it means in one sentence and where to read more.', intro: 'The studio uses the terms you will meet in papers, code and documentation. This page lists them with one sentence each. Point at an underlined term in the studio to see the same sentence there.', h: ['Term', 'In one sentence'], more: 'article' },
  ru: { title: 'Словарик терминов', desc: 'Все термины студии в одной таблице: перевод, объяснение в одну фразу и ссылка на статью.', intro: 'В подписях студии термины стоят так, как вы встретите их в статьях, коде и документации, чаще всего по-английски. Здесь у каждого есть перевод и объяснение в одну фразу. То же самое видно в студии, если навести на подчёркнутый термин.', h: ['Термин', 'По-русски', 'В подписях студии', 'В одну фразу'], more: 'статья' } };

// --- проверки
for (const l of G.langs) if (!D[l]) problems.push(`нет словаря интерфейса для языка ${l}`);
for (const t of G.terms) for (const l of G.langs) {
  if (!t[l] || !t[l].tip) problems.push(`${t.id}: нет объяснения (tip) для ${l}`);
  if (l !== 'en' && (!t[l] || !t[l].word)) problems.push(`${t.id}: нет перевода слова (word) для ${l}`);
}
const used = new Set();
for (const f of readdirSync(`${root}web`).filter((f) => /\.(html|js)$/.test(f))) {
  const s = readFileSync(`${root}web/${f}`, 'utf8');
  for (const m of s.matchAll(/data-term="([A-Za-z]+)"/g)) used.add(m[1]);
  for (const m of s.matchAll(/data-term="\$\{key\}"/g)) void m;      // ползунки: термин = ключ настройки, проверяются ниже по словарю
}
for (const id of used) for (const l of G.langs) if (!D[l]['gl.' + id]) problems.push(`термин «${id}» подчёркнут в интерфейсе, но подсказки gl.${id} для ${l} нет`);
for (const t of G.terms) for (const l of G.langs) for (const pat of (t[l] && t[l].avoid) || []) {
  const re = new RegExp(pat, 'i');
  for (const [k, v] of Object.entries(D[l])) { if (k.startsWith('gl.') || typeof v !== 'string') continue;
    if (re.test(v)) problems.push(`${l}: подпись ${k} = «${v.slice(0, 70)}» — по глоссарию термин пишется «${t[l].label || t.term}»`); }
}

// --- таблица для людей
const esc = (s) => String(s || '').replace(/\|/g, '\\|');
const others = G.langs.filter((l) => l !== 'en');
let md = `# Glossary of terms\n\nGenerated from \`web/i18n/glossary.js\` by \`node scripts/glossary.mjs\`. Do not edit this file: edit the source and run the script.\n\n` +
  `**The rule.** In labels a term is written the way a reader will meet it in papers, code and documentation. The translation and a one-sentence explanation appear when the reader points at the term, and on the terms page of Docs.\n\n` +
  `| Group | In labels | In a tooltip |\n| --- | --- | --- |\n` +
  `| keep | the industry term, in Latin letters in every language | English term · word. Explanation. |\n` +
  `| calque | the established word of the language | English term · word. Explanation. |\n` +
  `| translate | the translation | English term · word. Explanation. |\n\n` +
  `The group decides only what stands in a label. A tooltip always has the same order: the English term first, then the word in the reader's language, then the explanation.\n\n` +
  `To add a language: add its code to \`LANGS\` in the source and fill \`word\` and \`tip\` for every term (\`label\` and \`avoid\` where needed).\n\n## Terms\n\n` +
  `| Term | Group | Short | ${others.map((l) => `${NAME[l] || l}: word | ${NAME[l] || l}: in labels`).join(' | ')} | Docs | Source |\n| --- | --- | --- | ${others.map(() => '--- | ---').join(' | ')} | --- | --- |\n`;
for (const t of G.terms) md += `| ${esc(t.term)} | ${t.group} | ${esc(t.short)} | ${others.map((l) => `${esc(t[l].word)} | ${esc(t[l].label || (t.group === 'keep' ? t.term : t[l].word))}`).join(' | ')} | ${t.slug} | ${esc(t.source)} |\n`;
md += `\n## Explanations\n\n`;
for (const t of G.terms) md += `**${t.term}**\n\n${G.langs.map((l) => `- ${l}: ${G.tipOf(t, l).replace(/</g, '&lt;')}`).join('\n')}\n\n`;

// --- страница-словарик Docs
const code = (s) => String(s).replace(/<\|[a-z_]+\|>/g, (m) => '`' + m + '`').replace(/\|/g, '\\|').replace(/([{}])/g, '\\$1');
// На английском две колонки. На остальных языках порядок тот же, что в подсказках: английский термин, слово на языке
// читателя, затем как термин написан в подписях студии и объяснение.
const page = (l) => { const u = UI[l], rows = G.terms.map((t) => { const L = t[l], link = `[${u.more}](../glossary/${t.slug}/)`;
    if (l === 'en') return `| **${code(t.term)}** | ${code(L.tip)} ${link} |`;
    return `| **${code(t.term)}** | ${code(L.word)} | ${code(L.label || (t.group === 'keep' ? t.term : L.word))} | ${code(L.tip)} ${link} |`; });
  return `---\ntitle: ${JSON.stringify(u.title)}\ndescription: ${JSON.stringify(u.desc)}\n---\n\n${u.intro}\n\n| ${u.h.join(' | ')} |\n| ${u.h.map(() => '---').join(' | ')} |\n${rows.join('\n')}\n`; };

if (!checkOnly) {
  writeFileSync(`${root}web/i18n/GLOSSARY.md`, md);
  for (const l of G.langs) { if (!UI[l]) { problems.push(`нет текстов страницы-словарика для ${l} (UI в scripts/glossary.mjs)`); continue; }
    const dir = `${root}docsite/src/content/docs/${l === 'en' ? '' : l + '/'}docs`; mkdirSync(dir, { recursive: true }); writeFileSync(`${dir}/terms.mdx`, page(l)); }
}
console.log(`глоссарий: ${G.terms.length} терминов, языки: ${G.langs.join(', ')}; подчёркнутых терминов в интерфейсе: ${used.size}`);
if (problems.length) { console.error('ПРОБЛЕМЫ:\n- ' + problems.join('\n- ')); process.exit(1); }
console.log('проверка пройдена');
